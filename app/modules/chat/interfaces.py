"""
Chat Interfaces (app/modules/chat/interfaces.py)
modules/sql_guard now validates MongoDB aggregation pipelines; SQLGenerator now generates a MongoDB query spec; QueryExecutor now runs it on MongoDB.
Protocols for AI query execution, schema catalog, cache, and conversation persistence.
"""

from typing import Any, Dict, List, Optional, Protocol, Tuple


class QueryExecutorProtocol(Protocol):
    async def execute_query(
        self, query: Any, company_id: str, columns: Optional[List[str]] = None
    ) -> Tuple[List[Dict[str, str]], List[List[Any]], bool]: ...


class SQLGeneratorProtocol(Protocol):
    async def generate(
        self, question: str, catalog: Dict[str, Any], history: List[Dict[str, str]], company_id: str
    ) -> Dict[str, Any]: ...


class ChatCacheProtocol(Protocol):
    async def get(self, key: str) -> Optional[str]: ...
    async def set(self, key: str, value: str, ex: Optional[int] = None) -> bool: ...
    async def incr(self, key: str) -> int: ...
    async def expire(self, key: str, seconds: int) -> bool: ...


class ChatRepoProtocol(Protocol):
    async def get_tenant(self, company_id: str) -> Optional[Dict[str, Any]]: ...
    async def check_and_increment_rate_limits(self, company_id: str, user_id: str) -> None: ...
    async def increment_monthly_usage(self, company_id: str, tokens: int = 0) -> None: ...
    async def save_conversation(self, conv_doc: Dict[str, Any]) -> str: ...
    async def save_message(self, msg_doc: Dict[str, Any]) -> str: ...
    async def list_user_conversations(self, user_id: str, company_id: str) -> List[Dict[str, Any]]: ...
    async def get_schema_catalog(self, company_id: str) -> Dict[str, Any]: ...


class RecordSearchRepository(Protocol):
    async def search_records(
        self, company_id: str, query: str, limit: int = 3, min_score: float = 0.5
    ) -> List[Dict[str, Any]]: ...


class AnswerWriterProtocol(Protocol):
    async def write_answer(
        self, question: str, columns: List[Dict[str, str]], rows: List[List[Any]]
    ) -> Optional[str]: ...

